const mongoose = require("mongoose");

/*
=========================================================
StudentProgress

تقدم الطالب داخل المحتوى التعليمي.

نستخدمه لاحقًا لتسجيل:
- الدروس التي فتحها الطالب
- نسبة مشاهدة الفيديو
- تقدم PDF
- حالة إكمال الدرس
- آخر وقت للنشاط
=========================================================
*/


// =========================================================
// LESSON PROGRESS SCHEMA
// =========================================================

const lessonProgressSchema =
  new mongoose.Schema(
    {
      /*
      ==============================
      معرف الدرس
      ==============================
      */

      lessonId: {
        type: String,
        required: true,
      },


      /*
      ==============================
      الصف
      ==============================
      */

      gradeId: {
        type: String,
        default: null,
      },


      /*
      ==============================
      المادة
      ==============================
      */

      subjectId: {
        type: String,
        default: null,
      },


      /*
      ==============================
      الوحدة
      ==============================
      */

      unitId: {
        type: String,
        default: null,
      },


      /*
      ==============================
      عنوان الدرس
      ==============================
      */

      lessonTitle: {
        type: String,
        default: "",
      },


      /*
      ==============================
      نسبة الفيديو
      ==============================
      */

      videoProgress: {
        type: Number,
        min: 0,
        max: 100,
        default: 0,
      },


      /*
      ==============================
      نسبة PDF
      ==============================
      */

      pdfProgress: {
        type: Number,
        min: 0,
        max: 100,
        default: 0,
      },


      /*
      ==============================
      نسبة الدرس العامة
      ==============================
      */

      completionPercent: {
        type: Number,
        min: 0,
        max: 100,
        default: 0,
      },


      /*
      ==============================
      حالة الدرس
      ==============================
      */

      status: {
        type: String,

        enum: [
          "not_started",
          "in_progress",
          "completed",
        ],

        default:
          "not_started",
      },


      /*
      ==============================
      آخر فتح
      ==============================
      */

      lastOpenedAt: {
        type: Date,
        default: null,
      },


      /*
      ==============================
      وقت الإكمال
      ==============================
      */

      completedAt: {
        type: Date,
        default: null,
      },
    },

    {
      _id: false,
    }
  );


// =========================================================
// STUDENT PROGRESS SCHEMA
// =========================================================

const studentProgressSchema =
  new mongoose.Schema(
    {
      /*
      ==============================
      الطالب
      ==============================
      */

      userId: {
        type: String,
        required: true,
        unique: true,
        index: true,
      },


      /*
      ==============================
      الصف
      ==============================
      */

      gradeId: {
        type: String,
        default: null,
        index: true,
      },


      /*
      ==============================
      المرحلة
      ==============================
      */

      stageId: {
        type: String,
        default: null,
      },


      /*
      ==============================
      النظام التعليمي
      ==============================
      */

      systemId: {
        type: String,
        default: null,
      },


      /*
      ==============================
      الدروس
      ==============================
      */

      lessons: {
        type: [lessonProgressSchema],
        default: [],
      },


      /*
      ==============================
      إجمالي الدروس
      ==============================
      */

      totalLessons: {
        type: Number,
        min: 0,
        default: 0,
      },


      /*
      ==============================
      الدروس المكتملة
      ==============================
      */

      completedLessons: {
        type: Number,
        min: 0,
        default: 0,
      },


      /*
      ==============================
      الدروس قيد الدراسة
      ==============================
      */

      inProgressLessons: {
        type: Number,
        min: 0,
        default: 0,
      },


      /*
      ==============================
      نسبة إكمال المحتوى
      ==============================
      */

      overallCompletion: {
        type: Number,
        min: 0,
        max: 100,
        default: 0,
      },


      /*
      ==============================
      إجمالي وقت الدراسة
      ==============================
      */

      studyTimeSeconds: {
        type: Number,
        min: 0,
        default: 0,
      },


      /*
      ==============================
      آخر نشاط
      ==============================
      */

      lastActivityAt: {
        type: Date,
        default: null,
        index: true,
      },
    },
    {
      timestamps: true,
    }
  );


// =========================================================
// EXPORT
// =========================================================

module.exports =
  mongoose.model(
    "StudentProgress",
    studentProgressSchema
  );