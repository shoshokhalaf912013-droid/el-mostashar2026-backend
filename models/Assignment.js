// =========================================================
// backend/models/Assignment.js
// =========================================================

const mongoose = require("mongoose");

/*
=========================================================
Assignment
الواجب الدراسي

هذا الموديل مسؤول عن:
- إنشاء الواجب
- ربط الواجب بالطالب / الصف / المادة
- تحديد موعد التسليم
- تسجيل حالة التسليم
- تسجيل الدرجة
=========================================================
*/


// =========================================================
// SUBMISSION SCHEMA
// =========================================================

const submissionSchema =
  new mongoose.Schema(
    {
      /*
      ==============================
      الطالب
      ==============================
      */

      userId: {
        type: String,
        required: true,
        index: true,
      },


      /*
      ==============================
      حالة التسليم
      ==============================
      */

      status: {
        type: String,

        enum: [
          "pending",
          "submitted",
          "late",
          "missing",
          "graded",
        ],

        default: "pending",

        index: true,
      },


      /*
      ==============================
      وقت التسليم
      ==============================
      */

      submittedAt: {
        type: Date,
        default: null,
      },


      /*
      ==============================
      الدرجة
      ==============================
      */

      score: {
        type: Number,
        min: 0,
        default: null,
      },


      /*
      ==============================
      الدرجة الكاملة
      ==============================
      */

      totalMarks: {
        type: Number,
        min: 0,
        default: null,
      },


      /*
      ==============================
      ملاحظات المعلم
      ==============================
      */

      teacherComment: {
        type: String,
        default: "",
        trim: true,
      },


      /*
      ==============================
      رابط الملف
      ==============================
      */

      attachmentUrl: {
        type: String,
        default: "",
        trim: true,
      },
    },
    {
      _id: false,
    }
  );


// =========================================================
// ASSIGNMENT SCHEMA
// =========================================================

const assignmentSchema =
  new mongoose.Schema(
    {
      /*
      ==============================
      عنوان الواجب
      ==============================
      */

      title: {
        type: String,
        required: true,
        trim: true,
      },


      /*
      ==============================
      الوصف
      ==============================
      */

      description: {
        type: String,
        default: "",
        trim: true,
      },


      /*
      ==============================
      الصف
      ==============================
      */

      gradeId: {
        type: String,
        default: null,
        index: true,
      },


      /*
      ==============================
      المادة
      ==============================
      */

      subjectId: {
        type: String,
        default: null,
        index: true,
      },


      /*
      ==============================
      الوحدة
      ==============================
      */

      unitId: {
        type: String,
        default: null,
        index: true,
      },


      /*
      ==============================
      الدرس
      ==============================
      */

      lessonId: {
        type: String,
        default: null,
        index: true,
      },


      /*
      ==============================
      المعلم
      ==============================
      */

      teacherId: {
        type: String,
        default: null,
        index: true,
      },


      /*
      ==============================
      هل الواجب منشور؟
      ==============================
      */

      published: {
        type: Boolean,
        default: false,
        index: true,
      },


      /*
      ==============================
      الموعد النهائي
      ==============================
      */

      dueDate: {
        type: Date,
        default: null,
        index: true,
      },


      /*
      ==============================
      الدرجة الكاملة
      ==============================
      */

      totalMarks: {
        type: Number,
        min: 0,
        default: 100,
      },


      /*
      ==============================
      نص الواجب
      ==============================
      */

      instructions: {
        type: String,
        default: "",
      },


      /*
      ==============================
      رابط الملف
      ==============================
      */

      attachmentUrl: {
        type: String,
        default: "",
      },


      /*
      ==============================
      الطلاب المستهدفون
      ==============================

      إذا كانت فارغة:
      الواجب موجه لكل طلاب الصف المحدد.

      وإذا كانت تحتوي على IDs:
      الواجب موجه لهؤلاء الطلاب فقط.
      */

      assignedStudentIds: {
        type: [String],
        default: [],
      },


      /*
      ==============================
      عمليات التسليم
      ==============================
      */

      submissions: {
        type: [submissionSchema],
        default: [],
      },
    },
    {
      timestamps: true,
    }
  );


// =========================================================
// INDEXES
// =========================================================

assignmentSchema.index({
  gradeId: 1,
  subjectId: 1,
  dueDate: -1,
});

assignmentSchema.index({
  teacherId: 1,
  createdAt: -1,
});

assignmentSchema.index({
  "submissions.userId": 1,
  dueDate: -1,
});


// =========================================================
// EXPORT
// =========================================================

module.exports =
  mongoose.model(
    "Assignment",
    assignmentSchema
  );