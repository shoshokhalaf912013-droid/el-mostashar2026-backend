// models/Attempt.js

const mongoose = require("mongoose");

/*
========================================================
Attempt
محاولة الطالب للامتحان
========================================================
*/


// ======================================================
// إجابة السؤال
// ======================================================

const answerSchema = new mongoose.Schema(
  {
    /*
    ======================================================
    رقم السؤال داخل الامتحان
    ======================================================
    */

    questionIndex: {
      type: Number,
      required: true,
      min: 0,
    },


    /*
    ======================================================
    إجابة الاختيار من متعدد
    ======================================================

    0 = أ
    1 = ب
    2 = ج
    3 = د

    في السؤال المقالي تكون null
    */

    choiceIndex: {
      type: Number,
      min: 0,
      max: 3,
      default: null,
    },


    /*
    ======================================================
    الإجابة النصية للسؤال المقالي
    ======================================================

    الطالب يستطيع كتابة إجابته مباشرة.
    */

    textAnswer: {
      type: String,
      default: "",
      trim: true,
    },


    /*
    ======================================================
    صورة إجابة السؤال المقالي
    ======================================================

    سيتم تخزين رابط الصورة بعد رفعها.
    */

    imageUrl: {
      type: String,
      default: "",
      trim: true,
    },


    /*
    ======================================================
    درجة السؤال بعد تصحيح المدرس
    ======================================================

    null = لم يتم التصحيح بعد

    مثال:
    السؤال = 5 درجات
    المدرس أعطى الطالب = 4
    */

    awardedMarks: {
      type: Number,
      default: null,
      min: 0,
    },


    /*
    ======================================================
    تعليق المدرس
    ======================================================
    */

    teacherComment: {
      type: String,
      default: "",
      trim: true,
    },


    /*
    ======================================================
    حالة تصحيح السؤال
    ======================================================

    false = لم يتم التصحيح
    true  = تم التصحيح
    */

    graded: {
      type: Boolean,
      default: false,
    },
  },
  {
    _id: false,
  }
);


// ======================================================
// Attempt Schema
// ======================================================

const attemptSchema = new mongoose.Schema(
  {
    /*
    ==============================
    الامتحان
    ==============================
    */

    examId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Exam",
      required: true,
      index: true,
    },


    /*
    ==============================
    الطالب
    ==============================
    
    يأتي من JWT:
    
    req.user.id
    */

    userId: {
      type: String,
      default: null,
      index: true,
    },


    /*
    ==============================
    الإجابات
    ==============================
    
    تشمل الآن:
    
    MCQ
    - choiceIndex

    Essay
    - textAnswer
    - imageUrl
    - awardedMarks
    - teacherComment
    - graded
    */

    answers: {
      type: [answerSchema],
      default: [],
    },


    /*
    ==============================
    حالة المحاولة
    ==============================
    */

    status: {
      type: String,

      enum: [
        "in_progress",
        "submitted",
        "failed",
        "abandoned",
      ],

      default: "in_progress",

      index: true,
    },


    /*
    ==============================
    وقت بدء الامتحان
    ==============================
    */

    startedAt: {
      type: Date,
      default: Date.now,
    },


    /*
    ==============================
    آخر حفظ
    ==============================
    */

    lastSavedAt: {
      type: Date,
      default: Date.now,
    },


    /*
    ==============================
    آخر Ping
    ==============================
    */

    lastPingAt: {
      type: Date,
      default: Date.now,
    },


    /*
    ==============================
    وقت انتهاء الامتحان
    ==============================
    */

    endedAt: {
      type: Date,
      default: null,
    },


    /*
    ==============================
    الوقت المتبقي
    ==============================
    
    بالثواني
    */

    remainingSeconds: {
      type: Number,
      required: true,
      min: 0,
    },


    /*
    ==============================
    الدرجة
    ==============================
    
    الدرجة الحالية للمحاولة.

    في حالة وجود Essay:
    تحتوي في البداية على درجات MCQ
    ثم يتم تحديثها بعد تصحيح المقالي.
    */

    score: {
      type: Number,
      default: null,
      min: 0,
    },


    /*
    ==============================
    السماح بالاستكمال
    ==============================
    
    false في Strict Mode
    */

    allowResume: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);


// ======================================================
// Indexes
// ======================================================

/*
البحث عن محاولات الطالب في امتحان معين
*/

attemptSchema.index({
  userId: 1,
  examId: 1,
  createdAt: -1,
});


/*
البحث عن المحاولات قيد التنفيذ
*/

attemptSchema.index({
  userId: 1,
  status: 1,
});


/*
منع وجود أكثر من محاولة
قيد التنفيذ لنفس الطالب في نفس الامتحان.

ملاحظة:
هذا Partial Index حتى لا يمنع الطالب
من إعادة الامتحان بعد التسليم.
*/

attemptSchema.index(
  {
    userId: 1,
    examId: 1,
  },
  {
    unique: true,

    partialFilterExpression: {
      status: "in_progress",
      userId: {
        $type: "string",
      },
    },
  }
);


// ======================================================
// Pre Save
// ======================================================

attemptSchema.pre("save", function () {

  /*
  لا نسمح بالوقت بالسالب
  */

  if (
    typeof this.remainingSeconds ===
      "number" &&
    this.remainingSeconds < 0
  ) {
    this.remainingSeconds = 0;
  }


  /*
  لا نسمح أن تتجاوز درجة السؤال
  الدرجة القصوى هنا لأن الدرجة القصوى
  موجودة في Exam وليس Attempt.

  لذلك يتم التحقق من الحد الأقصى
  في Controller أثناء التصحيح.
  */


  /*
  إذا أصبحت المحاولة submitted
  أو failed أو abandoned
  نسجل وقت الانتهاء إذا لم يكن موجودًا.
  */

  if (
    [
      "submitted",
      "failed",
      "abandoned",
    ].includes(this.status)
  ) {

    if (!this.endedAt) {
      this.endedAt = new Date();
    }

  }

});


// ======================================================
// Export
// ======================================================

module.exports = mongoose.model(
  "Attempt",
  attemptSchema
);